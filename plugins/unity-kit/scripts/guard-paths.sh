#!/bin/sh
# unity-kit PreToolUse guard for Edit/Write/MultiEdit.
# Blocks (exit 2) writes to .meta files and to Library/ or Temp/ inside a Unity project.
# Reads the hook payload on stdin. Anything outside a Unity project passes.

# sed and grep return nothing on invalid UTF-8 in other locales; paths may contain any bytes.
export LC_ALL=C

input=$(cat)

# tool_input.file_path. Unescape just enough for paths first (\\ -> /, \/ -> /, \" -> '),
# so the field can be matched with [^"]* (backslashes inside brackets differ between GNU and BSD sed).
file=$(printf '%s' "$input" | tr -d '\n' |
  sed 's#\\\\#/#g; s#\\/#/#g; s#\\"#'"'"'#g' |
  sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
[ -n "$file" ] || exit 0

# Walk up from the file to the Unity project root (the folder with ProjectSettings/ProjectVersion.txt).
dir=$(dirname "$file")
root=""
while [ -n "$dir" ] && [ "$dir" != "/" ] && [ "$dir" != "." ]; do
  if [ -f "$dir/ProjectSettings/ProjectVersion.txt" ]; then root=$dir; break; fi
  parent=$(dirname "$dir")
  [ "$parent" = "$dir" ] && break
  dir=$parent
done
[ -n "$root" ] || exit 0

rel=${file#"$root"/}
case "$rel" in
  Library/*|Temp/*|library/*|temp/*)
    echo "unity-kit: blocked edit to $rel. Library/ and Temp/ are generated by Unity; change the source asset or setting instead." >&2
    exit 2 ;;
esac

case "$file" in
  *.meta)
    if [ -f "$file" ]; then
      echo "unity-kit: blocked edit to existing $rel. Unity owns .meta files (GUIDs and import settings); change import settings in the Editor." >&2
    else
      echo "unity-kit: blocked writing $rel by hand. Unity creates .meta files on import; if you moved an asset, move its old .meta with it instead." >&2
    fi
    exit 2 ;;
esac
exit 0
